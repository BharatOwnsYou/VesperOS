#!/usr/bin/env python3
"""Generates arch/x86_64/isr.S: the 32 CPU-exception entry stubs, the common save/restore path and the stub table.
Emitted as explicit instructions (no assembler macros) so GNU as and clang's integrated assembler agree exactly."""
import sys
ERR = {8, 10, 11, 12, 13, 14, 17, 21, 29, 30}        # vectors for which the CPU pushes an error code
o = []
w = o.append
w("/* GENERATED by tools/gen_isr.py - do not edit by hand.")
w(" * Every stub pushes a uniform frame [error code (real or dummy 0)] [vector] and jumps to isr_common, which saves")
w(" * all GPRs and calls exception_dispatch(trap_frame_t *). Layout seen by C is trap_frame_t in traps.c. */")
w("    .section .text")
w("    .code64")
for n in range(32):
    w(f"    .globl isr_stub_{n}")
    w(f"    .type isr_stub_{n}, @function")
    w(f"isr_stub_{n}:")
    if n not in ERR:
        w("    pushq   $0")
    w(f"    pushq   ${n}")
    w("    jmp     isr_common")
w("isr_common:")
for r in ["rax","rcx","rdx","rbx","rbp","rsi","rdi","r8","r9","r10","r11","r12","r13","r14","r15"]:
    w(f"    pushq   %{r}")
w("    cld")
w("    movq    %rsp, %rdi              /* arg0 = trap_frame_t *  (rsp is 16-byte aligned here: 22 qwords below an aligned CPU frame) */")
w("    call    exception_dispatch")
w("    /* only reached for exceptions the dispatcher chooses to survive (NMI) */")
for r in ["r15","r14","r13","r12","r11","r10","r9","r8","rdi","rsi","rbp","rbx","rdx","rcx","rax"]:
    w(f"    popq    %{r}")
w("    addq    $16, %rsp               /* drop vector + error code */")
w("    iretq")
w("")
w("    .section .rodata")
w("    .balign 8")
w("    .globl isr_stub_table")
w("isr_stub_table:")
for n in range(32):
    w(f"    .quad   isr_stub_{n}")
w('    .section .note.GNU-stack,"",@progbits')
sys.stdout.write("\n".join(o) + "\n")
