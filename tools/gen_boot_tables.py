#!/usr/bin/env python3
"""Generates arch/x86_64/boot_tables.S: the page tables the 32-bit boot stub loads before entering long mode.

They identity-map the first 4 GiB with 2 MiB pages (present | writable | page-size = 0x83), EXCEPT the first 2 MiB,
which uses 4 KiB pages: that region contains the legacy VGA/ROM hole (0xA0000-0xFFFFF), which the fixed-range MTRRs give
different memory types than the RAM around it. The Intel SDM (Vol.3, 11.11.8) says a large page spanning several MTRR
types gives undefined behaviour, and our kernel image and DMA buffers live in that very 2 MiB. 4 KiB pages let the hole
be mapped uncached (PWT|PCD) while the rest stays write-back (as Linux does). Everything the kernel
touches at boot - its own image at 1 MiB, the multiboot info block, PCI BARs below 4 GiB, a framebuffer below
4 GiB - is therefore reachable at virtual == physical, exactly as on the old 32-bit build, so no driver address
arithmetic changes. Addresses above 4 GiB are mapped on demand by mmio_map().

The tables are emitted as literal data (not assembler macros) so every assembler produces identical bytes."""
import sys
out = []
w = out.append
w("/* GENERATED by tools/gen_boot_tables.py - do not edit by hand. Identity map of 0..4 GiB, 2 MiB pages. */")
w('    .section .data')
w('    .balign 4096')
w('    .globl boot_pml4')
w('boot_pml4:')
w('    .quad boot_pdpt + 0x03')
w('    .fill 511, 8, 0')
w('    .balign 4096')
w('    .globl boot_pdpt')
w('boot_pdpt:')
for g in range(4):
    w(f'    .quad boot_pd{g} + 0x03')
w('    .fill 508, 8, 0')
for g in range(4):
    w('    .balign 4096')
    w(f'boot_pd{g}:')
    for i in range(512):
        if g == 0 and i == 0:
            w('    .quad boot_pt0 + 0x03            /* first 2 MiB: 4 KiB pages, see boot_pt0 */')
            continue
        phys = (g << 30) | (i << 21)
        w(f'    .quad 0x{phys | 0x83:016x}')
w('    .balign 4096')
w('boot_pt0:')
for i in range(512):
    phys = i << 12
    flags = 0x1B if 0xA0 <= i < 0x100 else 0x03        # 0xA0000-0xFFFFF: P|RW|PWT|PCD (uncached); rest P|RW (write-back)
    w(f'    .quad 0x{phys | flags:016x}')
w('    .section .note.GNU-stack,"",@progbits')
sys.stdout.write("\n".join(out) + "\n")
